#!/usr/bin/env python3
"""Skill helper: interview catalog, grading rubric, progress and Architecture Review.

Only needs PyYAML (pip install pyyaml). The engine and catalog are bundled next to this
file in ./antipatterns (generated by scripts/build_skill.py in the repository).

  aap.py topics
  aap.py search "idempotency payment" [--topic agent-frameworks] [--domain fintech]
  aap.py scenario rag-01 [--svg out.svg]
  aap.py question [--topic rag] [--domain telco] [--user me]
  aap.py rubric rag-01
  aap.py record rag-01 --met names_antipattern,concrete_fix [--user me]
  aap.py progress [--user me]
  aap.py spec-guide
  aap.py refs
  aap.py ref telco-sim-swap-agent > spec.yaml
  aap.py check spec.yaml
  aap.py review spec.yaml --out review-dir [--png]
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import yaml  # noqa: E402

from antipatterns import tools as T  # noqa: E402
from antipatterns.render import render_fix  # noqa: E402


def out(obj) -> None:
    if isinstance(obj, str):
        print(obj)
    else:
        print(yaml.safe_dump(obj, sort_keys=False, allow_unicode=True, width=100))


def main() -> None:
    p = argparse.ArgumentParser()
    sub = p.add_subparsers(dest="cmd", required=True)
    sub.add_parser("topics")
    s = sub.add_parser("search"); s.add_argument("query"); s.add_argument("--topic"); s.add_argument("--domain"); s.add_argument("--limit", type=int, default=8)
    s = sub.add_parser("scenario"); s.add_argument("id"); s.add_argument("--svg")
    s = sub.add_parser("question"); s.add_argument("--topic"); s.add_argument("--domain"); s.add_argument("--user", default="default")
    s = sub.add_parser("rubric"); s.add_argument("id")
    s = sub.add_parser("record"); s.add_argument("id"); s.add_argument("--met", default=""); s.add_argument("--user", default="default"); s.add_argument("--notes", default="")
    s = sub.add_parser("progress"); s.add_argument("--user", default="default")
    sub.add_parser("spec-guide")
    sub.add_parser("refs")
    s = sub.add_parser("ref"); s.add_argument("id")
    s = sub.add_parser("check"); s.add_argument("spec")
    s = sub.add_parser("review"); s.add_argument("spec"); s.add_argument("--out", required=True); s.add_argument("--png", action="store_true")
    a = p.parse_args()

    try:
        if a.cmd == "topics":
            out(T.list_topics())
        elif a.cmd == "search":
            out(T.search_scenarios(a.query, a.topic, a.domain, a.limit))
        elif a.cmd == "scenario":
            sc = T.get_scenario(a.id)
            if a.svg:
                Path(a.svg).write_text(render_fix({**sc["diagram"], "title": sc["title"]}))
                sc["diagram_svg_file"] = a.svg
            out(sc)
        elif a.cmd == "question":
            out(T.next_question(a.user, a.topic, a.domain))
        elif a.cmd == "rubric":
            out(T.grading_rubric(a.id))
        elif a.cmd == "record":
            met = {m.strip() for m in a.met.split(",") if m.strip()}
            out(T.record_attempt(a.id, {k: k in met for k in T.RUBRIC}, a.user, a.notes))
        elif a.cmd == "progress":
            out(T.get_progress(a.user))
        elif a.cmd == "spec-guide":
            out(T.architecture_spec_guide())
        elif a.cmd == "refs":
            out(T.list_reference_architectures())
        elif a.cmd == "ref":
            out(T.get_reference_architecture(a.id))
        elif a.cmd in ("check", "review"):
            spec = yaml.safe_load(Path(a.spec).read_text())
            if a.cmd == "check":
                out(T.check_architecture_spec(spec))
            else:
                res = T.review_architecture(spec, out_dir=a.out)
                if a.png:
                    try:
                        import cairosvg
                        for name in ("before", "after"):
                            cairosvg.svg2png(url=str(Path(a.out) / f"{name}.svg"),
                                             write_to=str(Path(a.out) / f"{name}.png"), output_width=1360)
                        res["files"]["before_png"] = str(Path(a.out) / "before.png")
                        res["files"]["after_png"] = str(Path(a.out) / "after.png")
                    except ImportError:
                        res["png_note"] = "pip install cairosvg for PNG output; SVGs were written."
                out({"title": res["title"], "files": res["files"],
                     "findings": [{k: f[k] for k in ("label", "title", "severity", "node_title")}
                                  | {"scenarios": [s["id"] for s in f["scenarios"]]} for f in res["findings"]]})
    except (ValueError, KeyError) as e:
        print(json.dumps({"error": str(e)}))
        sys.exit(1)


if __name__ == "__main__":
    main()
